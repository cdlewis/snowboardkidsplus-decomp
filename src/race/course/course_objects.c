    TaskVisualResource *resource;
    u16 cameraIndex;
    s16 turn;
    s32 dx, dz;

    if (gCurrentTask->resource14 == 0xFFFF) {
        while (1) {}
    }
    resource = (TaskVisualResource *)&gTaskMemoryPool[gCurrentTask->resource14];
